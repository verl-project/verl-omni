"""Snapshot isolation for materialized CPU rows; not an RL integration test."""

from dataclasses import dataclass

import numpy as np
import pytest
import torch
from tensordict import TensorDict
from verl.utils import tensordict_utils as tu

from verl_omni.workers.utils.cohort_data import freeze_cohort_data, value_digest


@dataclass(frozen=True)
class Metadata:
    values: dict


def sample():
    nested = torch.nested.nested_tensor([torch.tensor([1, 2]), torch.tensor([3])], layout=torch.jagged)
    data = TensorDict({"tokens": nested}, batch_size=[2])
    media = [
        {"audio": np.array([1.0, 2.0]), "features": [torch.tensor([4.0])]},
        {"audio": np.array([3.0, 4.0]), "features": [torch.tensor([5.0])]},
    ]
    tu.assign_non_tensor_stack(data, "media", media)
    tu.assign_non_tensor_data(data, "controls", Metadata({"array": np.array([6.0, 7.0])}))
    return data


def test_digest_remains_compatible_for_materialized_multimodal_values():
    value = {
        "audio": np.array([1.5, -2.0], dtype="<f4"),
        "tokens": torch.tensor([[1, 2], [3, 4]], dtype=torch.int64),
        "note": "AVQA",
    }
    # Identity receipts may be computed by different actor ranks. Preserve
    # the digest generated by the pre-refactor implementation.
    assert value_digest(value) == "b308a11aebc3c9c9597b8837cdc22c42b174193c52458ee60f47f660e0bfcc70"
    value["audio"][0] = 2.5
    assert value_digest(value) != "b308a11aebc3c9c9597b8837cdc22c42b174193c52458ee60f47f660e0bfcc70"


def test_snapshot_owns_nested_tokens_media_and_metadata():
    data = sample()
    snapshot = freeze_cohort_data(data)
    assert value_digest(data.get("tokens")) == value_digest(snapshot.get("tokens"))
    assert value_digest(data.get("media")) == value_digest(snapshot.get("media"))
    source_audio = data.get("media").tolist()[0]["audio"]
    frozen_audio = snapshot.get("media").tolist()[0]["audio"]
    assert not np.shares_memory(source_audio, frozen_audio)
    source_audio[0] = 99
    data.get("media").tolist()[0]["features"][0][0] = 99
    data.get("tokens").values()[0] = 99
    tu.get_non_tensor_data(data, "controls", default=None).values["array"][0] = 99
    assert frozen_audio[0] == 1
    assert snapshot.get("media").tolist()[0]["features"][0][0] == 4
    assert snapshot.get("tokens").values()[0] == 1
    assert tu.get_non_tensor_data(snapshot, "controls", default=None).values["array"][0] == 6
    frozen_audio[1] = 88
    assert source_audio[1] == 2


def test_object_array_nested_payload_is_copied():
    data = sample()
    payload = np.empty(1, dtype=object)
    payload[0] = {"wave": np.array([1.0, 2.0])}
    tu.assign_non_tensor_stack(data, "media", [{"audio": payload}, {"audio": payload}])
    snapshot = freeze_cohort_data(data)
    source = data.get("media").tolist()[0]["audio"]
    frozen = snapshot.get("media").tolist()[0]["audio"]
    assert not np.shares_memory(source, frozen)
    assert not np.shares_memory(source[0]["wave"], frozen[0]["wave"])
    source[0]["wave"][0] = 99
    assert frozen[0]["wave"][0] == 1


def test_shared_source_media_becomes_independent_between_snapshot_rows():
    data = sample()
    audio = np.array([1.0, 2.0])
    features = torch.tensor([3.0, 4.0])
    tu.assign_non_tensor_stack(data, "media", [{"audio": audio, "features": features}] * 2)
    snapshot = freeze_cohort_data(data)
    first, second = snapshot.get("media").tolist()
    assert not np.shares_memory(first["audio"], second["audio"])
    assert first["features"].untyped_storage().data_ptr() != second["features"].untyped_storage().data_ptr()
    first["audio"][0] = 99
    first["features"][0] = 99
    assert second["audio"][0] == audio[0] == 1
    assert second["features"][0] == features[0] == 3


def test_unsupported_media_fails_closed():
    data = sample()
    tu.assign_non_tensor_stack(data, "media", [{"audio": object()}, {"audio": object()}])
    with pytest.raises(TypeError, match="Unsupported"):
        freeze_cohort_data(data)
